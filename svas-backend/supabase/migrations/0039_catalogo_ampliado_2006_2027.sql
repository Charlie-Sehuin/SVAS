-- ── Rangos de suma de los modelos nuevos ─────────────────────────────────────
-- suma = base × factor de la aseguradora × depreciación del año, redondeada a USD 100.
-- Depreciación: 0.88 ^ (2026 − año) de 2015 a 2026; la de 2015 × 0.94 ^ (2015 − año) hacia atrás; 2027 = 1 / 0.88.
insert into svas.rango_suma_asegurada (aseguradora_id, modelo_id, anio, suma_minima, suma_maxima)
select a.id, mo.id, y.anio,
       round(n.base * dep.f * f.fmin / 100) * 100,
       round(n.base * dep.f * f.fmax / 100) * 100
  from _modelo_nuevo n
  join svas.marca ma on ma.nombre = n.marca
  join svas.modelo mo on mo.marca_id = ma.id and mo.nombre = n.modelo
  cross join _factor f
  join svas.aseguradora a on a.codigo_estrategia = f.codigo
  cross join lateral generate_series(n.desde, n.hasta) as y(anio)
  cross join lateral (select case
      when y.anio between 2015 and 2026 then power(0.88::numeric, 2026 - y.anio)
      when y.anio = 2027 then 1 / 0.88::numeric
      else power(0.88::numeric, 11) * power(0.94::numeric, 2015 - y.anio) end as f) dep
on conflict (aseguradora_id, modelo_id, anio) do nothing;

